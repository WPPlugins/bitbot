/**
 * FAQ hooks — Content tab's new FAQ section + the "auto-draft from gap"
 * flow originating on the Overview tab's Coverage Gaps card.
 *
 * The backend ships FAQs into the chat prompt at chat time, so every
 * create/update/delete invalidates the relevant queries but doesn't need
 * to wait for anything else — the next chat turn picks up the change.
 */
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { rpc } from '@/api/rpc'
import { toast } from '@/components/ui/Toast'
import type { Faq, FaqDraft } from '@/api/types'

export function useFaqs() {
  return useQuery({
    queryKey: ['faqs'],
    queryFn: async (): Promise<Faq[]> => {
      const res = await rpc<{ faqs: Faq[] }>('GetFaqs')
      if (!res.success) throw new Error(res.error)
      return res.data.faqs
    },
    staleTime: 30 * 1000,
  })
}

export function useCreateFaq() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (data: { question: string; answer: string; autoGenerated?: boolean; sourceTopic?: string | null }) => {
      const res = await rpc<{ faq: Faq }>('CreateFaq', data)
      if (!res.success) throw new Error(res.error)
      return res.data.faq
    },
    onSuccess: (newFaq) => {
      // Optimistic prepend so the new FAQ row appears immediately in the
      // list, then invalidate so the server-side ordering/derived fields
      // catch up in the background. Without this the list looked unchanged
      // until page reload.
      qc.setQueryData(['faqs'], (prev: Faq[] | undefined) =>
        prev ? [newFaq, ...prev.filter((f) => f.id !== newFaq.id)] : [newFaq]
      )
      qc.invalidateQueries({ queryKey: ['faqs'] })
      toast.success('FAQ added')
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not add FAQ'),
  })
}

export function useUpdateFaq() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (data: { id: string; question?: string; answer?: string; active?: boolean }) => {
      const res = await rpc<{ faq: Faq }>('UpdateFaq', data)
      if (!res.success) throw new Error(res.error)
      return res.data.faq
    },
    onSuccess: (updated) => {
      qc.setQueryData(['faqs'], (prev: Faq[] | undefined) =>
        prev ? prev.map((f) => (f.id === updated.id ? updated : f)) : prev
      )
      qc.invalidateQueries({ queryKey: ['faqs'] })
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not update FAQ'),
  })
}

export function useDeleteFaq() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (id: string) => {
      const res = await rpc<{ ok: true }>('DeleteFaq', { id })
      if (!res.success) throw new Error(res.error)
      return res.data
    },
    onSuccess: (_data, deletedId) => {
      qc.setQueryData(['faqs'], (prev: Faq[] | undefined) =>
        prev ? prev.filter((f) => f.id !== deletedId) : prev
      )
      qc.invalidateQueries({ queryKey: ['faqs'] })
      toast.success('FAQ removed')
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not delete FAQ'),
  })
}

export function useDeleteFaqs() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (ids: string[]) => {
      const res = await rpc<{ faqsDeleted: number }>('DeleteFaqs', { ids })
      if (!res.success) throw new Error(res.error)
      return res.data
    },
    onSuccess: (data, ids) => {
      qc.setQueryData(['faqs'], (prev: Faq[] | undefined) =>
        prev ? prev.filter((f) => !ids.includes(f.id)) : prev
      )
      qc.invalidateQueries({ queryKey: ['faqs'] })
      toast.success(`Deleted ${data.faqsDeleted} ${data.faqsDeleted === 1 ? 'FAQ' : 'FAQs'}`)
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not delete FAQs'),
  })
}

/**
 * Draft (don't save) a Q+A from a coverage gap. The Content tab calls
 * this when the admin lands from Overview's "Auto-draft FAQ →" CTA;
 * the resulting draft prefills the manual-add form for review.
 */
export function useDraftFaqFromGap() {
  return useMutation({
    mutationFn: async (data: { topic: string; examples: string[] }): Promise<FaqDraft> => {
      const res = await rpc<{ draft: FaqDraft }>('DraftFaqFromGap', data)
      if (!res.success) throw new Error(res.error)
      return res.data.draft
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not draft FAQ'),
  })
}

/**
 * Discard a coverage-gap suggestion. Persists server-side (by topic) so it
 * stays gone across the 15-min insight recompute, then refreshes the
 * insights bundle so the pill disappears from the FAQ tab + Overview card.
 */
export function useDismissCoverageGap() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (topic: string): Promise<void> => {
      const res = await rpc<{ success: true }>('DismissCoverageGap', { topic })
      if (!res.success) throw new Error(res.error)
    },
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ['overview-insights'] })
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not discard suggestion'),
  })
}

/** Bring back every discarded coverage-gap suggestion for this site. */
export function useResetDismissedCoverageGaps() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (): Promise<void> => {
      const res = await rpc<{ success: true }>('ResetDismissedCoverageGaps', {})
      if (!res.success) throw new Error(res.error)
    },
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ['overview-insights'] })
    },
    onError: (err) => toast.error(err instanceof Error ? err.message : 'Could not reset suggestions'),
  })
}
