/**
 * Build tab: the field editor plus a live preview that validates answers.
 * Name and Email are fixed rows (the public forms require them): label and
 * placeholder stay editable, the key, type and required flag do not.
 */
import { useState } from 'react'
import type { FormFieldSchema } from '@/api/types'
import { isChoiceType, isLockedField, validateAnswers, withStableKey } from '@/lib/formSchema'

const FIELD_TYPES: { value: FormFieldSchema['type']; label: string }[] = [
  { value: 'text',     label: 'Text' },
  { value: 'email',    label: 'Email' },
  { value: 'phone',    label: 'Phone' },
  { value: 'textarea', label: 'Long text' },
  { value: 'select',   label: 'Dropdown' },
  { value: 'radio',    label: 'Single choice' },
  { value: 'checkbox', label: 'Multi-choice' },
]

interface BuildTabProps {
  fields: FormFieldSchema[]
  onChange: (next: FormFieldSchema[]) => void
  problems: string[]
}

export function BuildTab({ fields, onChange, problems }: BuildTabProps) {
  const move = (idx: number, dir: -1 | 1) => {
    const next = fields.slice()
    const target = idx + dir
    if (target < 0 || target >= next.length) return
    ;[next[idx], next[target]] = [next[target], next[idx]]
    onChange(next)
  }
  // The key is generated once, the first time a field gets a label, and is
  // never regenerated by later label edits (saved answers stay attached).
  const update = (idx: number, patch: Partial<FormFieldSchema>) => {
    onChange(fields.map((f, i) => (i === idx ? withStableKey({ ...f, ...patch }, fields) : f)))
  }
  const remove = (idx: number) => onChange(fields.filter((_, i) => i !== idx))
  const add = () => onChange([...fields, { name: '', label: '', type: 'text', required: false, placeholder: '' }])

  return (
    <div className="bb-form-build-grid">
      <section className="bb-form-build-editor">
        <h4 className="bb-form-build-heading">Fields</h4>
        <ul className="bb-form-build-list">
          {fields.map((f, idx) => {
            const locked = isLockedField(f)
            const needsOptions = isChoiceType(f.type) && (f.options ?? []).every((o) => !o.trim())
            return (
              <li key={idx} className="bb-form-build-row">
                <div className="bb-form-build-row-top">
                  <input
                    className="bb-input bb-form-build-label"
                    aria-label="Field label"
                    value={f.label}
                    onChange={(e) => update(idx, { label: e.target.value })}
                    placeholder="Field label (e.g. Your name)"
                  />
                  <select
                    className="bb-input bb-form-build-type"
                    aria-label="Field type"
                    value={f.type}
                    disabled={locked}
                    onChange={(e) => update(idx, { type: e.target.value as FormFieldSchema['type'] })}
                  >
                    {FIELD_TYPES.map((t) => <option key={t.value} value={t.value}>{t.label}</option>)}
                  </select>
                </div>
                <input
                  className="bb-input bb-form-build-placeholder"
                  aria-label="Placeholder"
                  value={f.placeholder ?? ''}
                  onChange={(e) => update(idx, { placeholder: e.target.value })}
                  placeholder="Placeholder (optional)"
                />
                <div className="bb-form-build-row-bottom">
                  <label className="bb-form-build-required">
                    <input
                      type="checkbox"
                      checked={locked ? true : f.required}
                      disabled={locked}
                      onChange={(e) => update(idx, { required: e.target.checked })}
                    />
                    Required
                  </label>
                  {locked && (
                    <span className="bb-form-build-lock" title="Every form needs this field">
                      Fixed field: visitors always give their {f.name}.
                    </span>
                  )}
                  <button className="bb-link-btn" onClick={() => move(idx, -1)} disabled={idx === 0} aria-label="Move up">↑</button>
                  <button className="bb-link-btn" onClick={() => move(idx, 1)} disabled={idx === fields.length - 1} aria-label="Move down">↓</button>
                  {!locked && (
                    <button className="bb-link-btn bb-form-build-remove" onClick={() => remove(idx)} aria-label="Remove field">Remove</button>
                  )}
                </div>
                {isChoiceType(f.type) && (
                  <>
                    <textarea
                      className="bb-input bb-textarea bb-form-build-options"
                      rows={3}
                      aria-label="Options, one per line"
                      aria-invalid={needsOptions}
                      placeholder={'One option per line\nMorning\nAfternoon\nEvening'}
                      value={(f.options ?? []).join('\n')}
                      onChange={(e) => update(idx, { options: e.target.value.split('\n') })}
                    />
                    {needsOptions && <p className="bb-field-help bb-field-help-error">Add at least one option.</p>}
                  </>
                )}
              </li>
            )
          })}
        </ul>
        <button className="bb-btn bb-btn-ghost bb-btn-small" onClick={add}>+ Add field</button>
        {problems.length > 0 && (
          <ul className="bb-form-build-problems" role="alert">
            {problems.map((p) => <li key={p}>{p}</li>)}
          </ul>
        )}
      </section>

      <aside className="bb-form-build-preview">
        <h4 className="bb-form-build-heading">Live preview</h4>
        <FormPreview fields={fields} />
      </aside>
    </div>
  )
}

type Answers = Record<string, string | string[]>

function FormPreview({ fields }: { fields: FormFieldSchema[] }) {
  const [answers, setAnswers] = useState<Answers>({})
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [checked, setChecked] = useState(false)
  const keyOf = (f: FormFieldSchema) => f.name || f.label
  const set = (f: FormFieldSchema, v: string | string[]) => {
    setAnswers((a) => ({ ...a, [keyOf(f)]: v }))
    setChecked(false)
  }
  const toggle = (f: FormFieldSchema, opt: string) => {
    const cur = Array.isArray(answers[keyOf(f)]) ? (answers[keyOf(f)] as string[]) : []
    set(f, cur.includes(opt) ? cur.filter((o) => o !== opt) : [...cur, opt])
  }

  const onSubmit = (e: React.FormEvent) => {
    e.preventDefault()
    const next = validateAnswers(fields, answers)
    setErrors(next)
    setChecked(Object.keys(next).length === 0)
  }

  return (
    <form className="bb-form-preview" onSubmit={onSubmit} noValidate>
      {fields.map((f, idx) => {
        const key = keyOf(f)
        const err = errors[key]
        const opts = (f.options ?? []).filter((o) => o.trim())
        const common = { 'aria-invalid': !!err, 'aria-label': f.label || 'Field' }
        return (
          <div key={idx} className="bb-form-preview-row">
            <span className="bb-form-preview-label">{f.label || '(no label)'}{f.required && ' *'}</span>
            {f.type === 'textarea' && (
              <textarea {...common} className="bb-input bb-textarea" rows={3} placeholder={f.placeholder}
                value={(answers[key] as string) ?? ''} onChange={(e) => set(f, e.target.value)} />
            )}
            {f.type === 'select' && (
              <select {...common} className="bb-input" value={(answers[key] as string) ?? ''} onChange={(e) => set(f, e.target.value)}>
                <option value="">Choose…</option>
                {opts.map((o) => <option key={o} value={o}>{o}</option>)}
              </select>
            )}
            {f.type === 'radio' && (
              <div className="bb-form-preview-choices" role="radiogroup" aria-label={f.label || 'Field'}>
                {opts.map((o) => (
                  <label key={o}><input type="radio" name={`pv-${key}`} checked={answers[key] === o} onChange={() => set(f, o)} /> {o}</label>
                ))}
              </div>
            )}
            {f.type === 'checkbox' && (
              <div className="bb-form-preview-choices" role="group" aria-label={f.label || 'Field'}>
                {opts.map((o) => (
                  <label key={o}>
                    <input type="checkbox" checked={Array.isArray(answers[key]) && (answers[key] as string[]).includes(o)} onChange={() => toggle(f, o)} /> {o}
                  </label>
                ))}
              </div>
            )}
            {(f.type === 'text' || f.type === 'email' || f.type === 'phone') && (
              <input {...common} className="bb-input" type={f.type === 'phone' ? 'tel' : 'text'}
                placeholder={f.placeholder} value={(answers[key] as string) ?? ''} onChange={(e) => set(f, e.target.value)} />
            )}
            {err && <span className="bb-field-help bb-field-help-error" role="alert">{err}</span>}
          </div>
        )
      })}
      <button type="submit" className="bb-btn bb-btn-primary bb-form-preview-submit">Check answers</button>
      <p className="bb-field-help" role="status">
        {checked ? 'Looks good. Nothing is sent from the preview.' : 'Try the form here. Nothing is sent from the preview.'}
      </p>
    </form>
  )
}
