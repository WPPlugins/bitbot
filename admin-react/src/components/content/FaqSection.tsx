/**
 * FAQs sub tab of the Knowledgebase.
 *
 * One card: a toolbar (search on long lists, the single count, + Add FAQ),
 * then the unanswered questions visitors asked (pills that draft an FAQ),
 * then the list. A new FAQ opens right under the toolbar; Edit opens in
 * place of the row. Rows keep multi-select with bulk delete.
 *
 * The Overview "Auto-draft FAQ" link still works: it stashes the question in
 * sessionStorage, which this section consumes on mount/popstate and routes
 * through the same draft pipeline.
 */
import { useEffect, useMemo, useState, useRef } from 'react'
import { useFaqs, useCreateFaq, useUpdateFaq, useDeleteFaq, useDeleteFaqs, useDraftFaqFromGap, useDismissCoverageGap, useResetDismissedCoverageGaps } from '@/hooks/useFaqs'
import { useOverviewInsights } from '@/hooks/useOverview'
import { ViewAllModal } from '@/components/ui/ViewAllModal'
import { WaitDots } from '@/components/ui/WaitDots'
import { confirm } from '@/components/ui/ConfirmDialog'
import { relativeTime } from '@/lib/utils'
import { allVisibleChecked, faqCountText, showFaqSearch, toggleVisible, visibleFaqList } from '@/lib/faqList'
import type { Faq, CoverageGap } from '@/api/types'

interface ComposerProps {
  /** When non-null, the composer is in "edit" mode for this FAQ. */
  editing?: Faq | null
  initialQuestion?: string
  initialAnswer?: string
  initialSourceTopic?: string | null
  initialAutoGenerated?: boolean
  /** Banner copy shown above the fields. Used for auto-draft hints. */
  banner?: string | null
  onClose: () => void
}

function FaqComposer({
  editing = null,
  initialQuestion = '',
  initialAnswer = '',
  initialSourceTopic = null,
  initialAutoGenerated = false,
  banner = null,
  onClose,
}: ComposerProps) {
  const [question, setQuestion] = useState(editing?.question ?? initialQuestion)
  const [answer, setAnswer] = useState(editing?.answer ?? initialAnswer)
  const create = useCreateFaq()
  const update = useUpdateFaq()

  // Sync when parent feeds new initial values (auto-draft arrival or
  // switching between FAQs being edited).
  useEffect(() => { setQuestion(editing?.question ?? initialQuestion) }, [editing?.id, initialQuestion])
  useEffect(() => { setAnswer(editing?.answer ?? initialAnswer) }, [editing?.id, initialAnswer])

  const isEditing = !!editing
  const pending = create.isPending || update.isPending

  const onSave = () => {
    const q = question.trim()
    const a = answer.trim()
    if (!q || !a) return
    if (isEditing && editing) {
      update.mutate(
        { id: editing.id, question: q, answer: a },
        { onSuccess: () => onClose() },
      )
    } else {
      create.mutate(
        {
          question: q,
          answer: a,
          autoGenerated: initialAutoGenerated,
          sourceTopic: initialSourceTopic,
        },
        { onSuccess: () => onClose() },
      )
    }
  }

  return (
    <div className="bb-faq-composer">
      {banner && (
        <div className="bb-faq-composer-hint">{banner}</div>
      )}
      <label className="bb-faq-field">
        <span className="bb-faq-field-label">Question</span>
        <input
          className="bb-input"
          type="text"
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          placeholder="e.g. Do you ship internationally?"
          maxLength={250}
          autoFocus
        />
      </label>
      <label className="bb-faq-field">
        <span className="bb-faq-field-label">Answer</span>
        <textarea
          className="bb-input bb-textarea"
          rows={4}
          value={answer}
          onChange={(e) => setAnswer(e.target.value)}
          placeholder="2-4 sentences. The bot will use this verbatim."
          maxLength={2000}
        />
      </label>
      <div className="bb-faq-composer-actions">
        <span className="bb-faq-composer-chars">{answer.length}/2000</span>
        <div className="bb-faq-composer-buttons">
          <button
            type="button"
            className="bb-btn bb-btn-ghost bb-btn-small"
            onClick={onClose}
          >
            {isEditing ? 'Cancel' : 'Discard'}
          </button>
          <button
            type="button"
            className="bb-btn bb-btn-primary"
            disabled={!question.trim() || !answer.trim() || pending}
            onClick={onSave}
          >
            {pending ? 'Saving…' : isEditing ? 'Save changes' : 'Add FAQ →'}
          </button>
        </div>
      </div>
    </div>
  )
}

interface GapPrefill {
  topic: string
  example: string
}

/**
 * Composer state machine. Three modes:
 *   - { mode: 'closed' }     — list view only, nothing to compose
 *   - { mode: 'new', ... }   — adding (manual or auto-drafted)
 *   - { mode: 'edit', faq }  — editing an existing FAQ
 */
type ComposerState =
  | { mode: 'closed' }
  | { mode: 'new'; question: string; answer: string; sourceTopic: string | null; autoGenerated: boolean; banner: string | null }
  | { mode: 'edit'; faq: Faq }

const FAQ_ACTIVE_CAP = 20
export function FaqSection() {
  const { data: faqs, isLoading: faqsLoading } = useFaqs()
  const { data: insights } = useOverviewInsights()
  const draftMutation = useDraftFaqFromGap()
  const dismissGap = useDismissCoverageGap()
  const resetGaps = useResetDismissedCoverageGaps()
  const del = useDeleteFaq()
  const delMany = useDeleteFaqs()

  // Multi-select state — checkbox per row + select-all + bulk-delete
  // toolbar that appears only when something is selected.
  const [checked, setChecked] = useState<Set<string>>(new Set())
  const checkedIds = useMemo(() => {
    const list = faqs ?? []
    const valid = new Set<string>()
    for (const f of list) if (checked.has(f.id)) valid.add(f.id)
    return valid
  }, [faqs, checked])
  const checkedCount = checkedIds.size
  const toggleOne = (id: string) => {
    setChecked((prev) => {
      const next = new Set(prev)
      if (next.has(id)) next.delete(id)
      else next.add(id)
      return next
    })
  }
  const clearChecks = () => setChecked(new Set())
  const runBulkDelete = async () => {
    const ids = Array.from(checkedIds)
    if (ids.length === 0) return
    const ok = await confirm({
      title: `Delete ${ids.length} ${ids.length === 1 ? 'FAQ' : 'FAQs'}?`,
      message: `The bot will stop using ${ids.length === 1 ? 'this answer' : 'these answers'} immediately. This cannot be undone.`,
      confirmLabel: `Delete ${ids.length}`,
      danger: true,
    })
    if (!ok) return
    await delMany.mutateAsync(ids).catch(() => null)
    clearChecks()
  }
  const composerRef = useRef<HTMLElement | null>(null)
  const [composer, setComposer] = useState<ComposerState>({ mode: 'closed' })
  const composerModeRef = useRef(composer.mode)
  composerModeRef.current = composer.mode
  const [showAllSuggestions, setShowAllSuggestions] = useState(false)
  const [query, setQuery] = useState('')

  const addButtonRef = useRef<HTMLButtonElement | null>(null)

  // Closing hands focus back to the control that opened the composer: the row's Edit, or + Add FAQ.
  const closeComposer = () => {
    const editedId = composer.mode === 'edit' ? composer.faq.id : null
    setComposer({ mode: 'closed' })
    requestAnimationFrame(() => {
      // The edited row may be gone (the search no longer matches it): fall back to + Add FAQ.
      const editButton = editedId
        ? document.querySelector<HTMLButtonElement>(`[data-faq-edit="${CSS.escape(editedId)}"]`)
        : null
      ;(editButton ?? addButtonRef.current)?.focus()
    })
  }

  // Cap: 20 active FAQs per site (Chat.ts flat-fetches the first 20;
  // anything beyond never reaches the bot prompt). Inactive FAQs don't
  // count. Future vector retrieval will lift this; see Obsidian
  // "Known Issues & Tech Debt" → FAQ retrieval.
  const activeFaqCount = (faqs ?? []).filter((f) => f.active).length
  const atFaqCap = activeFaqCount >= FAQ_ACTIVE_CAP

  const scrollToComposer = () => {
    requestAnimationFrame(() => {
      composerRef.current?.scrollIntoView({ behavior: 'smooth', block: 'nearest' })
    })
  }

  const openManual = () => {
    setComposer({
      mode: 'new',
      question: '',
      answer: '',
      sourceTopic: null,
      autoGenerated: false,
      banner: null,
    })
    scrollToComposer()
  }

  const openEdit = (faq: Faq) => {
    setComposer({ mode: 'edit', faq })
    scrollToComposer()
  }

  const draftFromGap = (gap: CoverageGap) => {
    draftMutation.mutate(
      { topic: gap.topic, examples: [gap.example].filter(Boolean) },
      {
        onSuccess: (draft) => {
          // An editor opened while this was drafting keeps its text: the late draft is dropped.
          if (composerModeRef.current === 'edit') return
          setComposer({
            mode: 'new',
            question: draft.question,
            answer: draft.answer,
            sourceTopic: gap.topic,
            autoGenerated: true,
            banner: `Drafted from an unanswered question. Check it before saving. Topic: ${gap.topic}.`,
          })
          // Close the modal if the user triggered the draft from there.
          setShowAllSuggestions(false)
          scrollToComposer()
        },
      },
    )
  }

  // Consume the sessionStorage stash from Overview's "Auto-draft FAQ →"
  // deep link. Runs on mount and on popstate so a return visit to the
  // tab picks up a fresh stash.
  useEffect(() => {
    const consume = () => {
      const raw = sessionStorage.getItem('bb-faq-from-gap')
      if (!raw) return
      sessionStorage.removeItem('bb-faq-from-gap')
      let parsed: GapPrefill
      try { parsed = JSON.parse(raw) } catch { return }
      if (!parsed.topic) return
      draftFromGap({ topic: parsed.topic, example: parsed.example, count: 0 })
    }
    consume()
    const onPop = () => consume()
    window.addEventListener('popstate', onPop)
    return () => window.removeEventListener('popstate', onPop)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  // Filter out gaps that already have a matching FAQ. Source-topic
  // match is case-insensitive so "Returns Policy" and "returns policy"
  // collapse together.
  const suggestableGaps = useMemo(() => {
    const allGaps = insights?.coverageGaps ?? []
    const existingTopics = new Set(
      (faqs ?? [])
        .map(f => (f.sourceTopic ?? '').trim().toLowerCase())
        .filter(Boolean)
    )
    return allGaps.filter(g => !existingTopics.has(g.topic.trim().toLowerCase()))
  }, [insights?.coverageGaps, faqs])

  // How many gaps the admin discarded — drives the "Reset discarded" link.
  const dismissedGapCount = insights?.dismissedGapCount ?? 0

  const onDeleteFaq = async (faq: Faq) => {
    const ok = await confirm({
      title: 'Delete this FAQ?',
      message: `"${faq.question.slice(0, 60)}" will be removed. This cannot be undone.`,
      confirmLabel: 'Delete',
      danger: true,
    })
    if (!ok) return
    del.mutate(faq.id)
  }

  // Composer banner copy for editing mode — keeps the surface honest
  // about what mode it's in even when the user lands on it directly.
  const editingBanner = composer.mode === 'edit'
    ? `Editing FAQ${composer.faq.autoGenerated && composer.faq.sourceTopic ? ` · originally drafted from "${composer.faq.sourceTopic}"` : ''}`
    : null

  const editingId = composer.mode === 'edit' ? composer.faq.id : null

  const total = faqs?.length ?? 0
  const offCount = total - activeFaqCount
  const visibleFaqs = visibleFaqList(faqs ?? [], query, editingId)
  const visibleIds = visibleFaqs.map((f) => f.id)
  const showSearch = showFaqSearch(total, query)
  // Select all works on the rows on screen, never on rows a search is hiding.
  const allChecked = allVisibleChecked(visibleIds, checkedIds)
  const toggleAll = () => setChecked(toggleVisible(visibleIds, checkedIds))
  // While an answer is being drafted the composer is spoken for: no second editor may open under it.
  const drafting = draftMutation.isPending
  const hasGaps = suggestableGaps.length > 0 || dismissedGapCount > 0

  return (
    <section id="faqs" className="bb-faq-section">
      <div className="bb-faq-card">
        {/* One toolbar: search (long lists only), the single count, the one primary action. */}
        <div className="bb-faq-toolbar">
          {showSearch && (
            <input
              className="bb-input bb-faq-search"
              type="search"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Search FAQs"
              aria-label="Search FAQs"
            />
          )}
          <span className="bb-faq-count">
            {faqsLoading ? 'Loading…' : faqCountText(activeFaqCount, FAQ_ACTIVE_CAP, offCount)}
          </span>
          <button
            type="button"
            className="bb-btn bb-btn-primary bb-btn-small"
            onClick={openManual}
            ref={addButtonRef}
            disabled={atFaqCap || drafting}
            title={atFaqCap ? `FAQ limit (${FAQ_ACTIVE_CAP}) reached. Edit or delete one to add another.` : undefined}
          >
            + Add FAQ
          </button>
        </div>

        {atFaqCap && (
          <p className="bb-faq-cap-help">
            FAQ limit reached ({FAQ_ACTIVE_CAP}). Edit or delete an existing FAQ to add a new one.
          </p>
        )}

        {/* Questions visitors asked that the bot could not answer: the reason to add an FAQ, so they lead. */}
        {hasGaps && (
          <div className="bb-faq-gaps">
            <div className="bb-faq-gaps-head">
              <span className="bb-faq-gaps-title">
                Unanswered questions
                {suggestableGaps.length > 0 && <span className="bb-faq-gaps-count">{suggestableGaps.length}</span>}
              </span>
              <span className="bb-faq-list-aside">
                {suggestableGaps.length === 0 && 'All discarded'}
                {suggestableGaps.length > 5 && (
                  <button type="button" className="bb-link-btn bb-faq-viewall" onClick={() => setShowAllSuggestions(true)}>
                    View all
                  </button>
                )}
                {dismissedGapCount > 0 && (
                  <button
                    type="button"
                    className="bb-faq-reset-icon"
                    disabled={resetGaps.isPending}
                    onClick={() => resetGaps.mutate()}
                    title="Reset"
                    aria-label={`Reset ${dismissedGapCount} discarded suggestion${dismissedGapCount === 1 ? '' : 's'}`}
                  >
                    ↺
                  </button>
                )}
              </span>
            </div>
            {suggestableGaps.length > 0 && (
              <div className="bb-faq-pills">
                {suggestableGaps.slice(0, 5).map((g, i) => (
                  <span key={i} className="bb-faq-pill-wrap">
                    <button
                      type="button"
                      className="bb-faq-pill bb-faq-pill-suggest"
                      disabled={draftMutation.isPending || atFaqCap}
                      onClick={() => draftFromGap(g)}
                      title={atFaqCap ? 'FAQ limit reached. Edit or delete an existing one first.' : g.example}
                    >
                      {g.topic}
                      <span className="bb-faq-pill-count">{g.count}</span>
                    </button>
                    <button
                      type="button"
                      className="bb-faq-pill-discard"
                      aria-label={`Discard suggestion: ${g.topic}`}
                      title="Discard"
                      disabled={dismissGap.isPending}
                      onClick={() => dismissGap.mutate(g.topic)}
                    >
                      ×
                    </button>
                  </span>
                ))}
              </div>
            )}
          </div>
        )}

        {/* New FAQ (typed, or drafted from an unanswered question) opens here, right under the button. */}
        {draftMutation.isPending && <div className="bb-faq-drafting" role="status">Drafting an answer<WaitDots /></div>}
        {!draftMutation.isPending && composer.mode === 'new' && (
          <div ref={(el) => { composerRef.current = el }} className="bb-faq-composer-slot">
            <FaqComposer
              initialQuestion={composer.question}
              initialAnswer={composer.answer}
              initialSourceTopic={composer.sourceTopic}
              initialAutoGenerated={composer.autoGenerated}
              banner={composer.banner}
              onClose={closeComposer}
            />
          </div>
        )}

        {checkedCount > 0 && (
          <div className="bb-faq-bulk-toolbar" role="region" aria-label="Bulk actions">
            {/* One place for selection: tick all, the count, and what to do with them. */}
            <label className="bb-faq-select-all">
              <input
                type="checkbox"
                className="bb-faq-row-check"
                checked={allChecked}
                onChange={toggleAll}
                aria-label={allChecked ? 'Deselect all FAQs' : 'Select all FAQs'}
              />
              <span><strong>{checkedCount}</strong> selected</span>
            </label>
            <div className="bb-faq-bulk-actions">
              <button type="button" className="bb-btn bb-btn-ghost bb-btn-small" onClick={clearChecks}>
                Clear
              </button>
              <button type="button" className="bb-btn bb-btn-danger bb-btn-small" onClick={runBulkDelete} disabled={delMany.isPending}>
                {delMany.isPending ? 'Deleting…' : `Delete ${checkedCount}`}
              </button>
            </div>
          </div>
        )}

        {!faqsLoading && total === 0 && composer.mode === 'closed' && (
          <p className="bb-faq-empty">
            {hasGaps ? 'No FAQs yet. Add one, or pick an unanswered question above.' : 'No FAQs yet.'}
          </p>
        )}
        {!faqsLoading && total > 0 && visibleFaqs.length === 0 && (
          <p className="bb-faq-empty">No FAQs match your search.</p>
        )}

        {visibleFaqs.length > 0 && (
          <ul className="bb-faq-list">
            {visibleFaqs.map((f) =>
              editingId === f.id && composer.mode === 'edit' ? (
                // Editing happens in place, where the row is.
                <li key={f.id} className="bb-faq-row bb-faq-row-editing" ref={(el) => { composerRef.current = el }}>
                  <FaqComposer editing={composer.faq} banner={editingBanner} onClose={closeComposer} />
                </li>
              ) : (
                <li key={f.id} className={`bb-faq-row ${checkedIds.has(f.id) ? 'bb-faq-row-selected' : ''}`}>
                  <input
                    type="checkbox"
                    className="bb-faq-row-check"
                    checked={checkedIds.has(f.id)}
                    onChange={() => toggleOne(f.id)}
                    aria-label={`Select FAQ: ${f.question.slice(0, 60)}`}
                  />
                  <div className="bb-faq-row-body">
                    <p className="bb-faq-question">
                      {f.question}
                      {f.autoGenerated && <span className="bb-faq-tag bb-faq-tag-auto">Auto</span>}
                    </p>
                    <p className="bb-faq-answer">{f.answer}</p>
                  </div>
                  <div className="bb-faq-row-side">
                    <span
                      className="bb-faq-row-time"
                      title={f.sourceTopic ? `From the unanswered question: ${f.sourceTopic}` : undefined}
                    >
                      Added {relativeTime(f.createdAt)}
                    </span>
                    <div className="bb-faq-row-controls">
                      <button type="button" className="bb-faq-row-ctrl" data-faq-edit={f.id} disabled={drafting} onClick={() => openEdit(f)}>
                        Edit
                      </button>
                      <button type="button" className="bb-faq-row-ctrl bb-faq-row-ctrl-danger" onClick={() => onDeleteFaq(f)}>
                        Delete
                      </button>
                    </div>
                  </div>
                </li>
              ),
            )}
          </ul>
        )}
      </div>

      {/* ── View-all modal ───────────────────────────────────────── */}
      <ViewAllModal
        open={showAllSuggestions}
        title="Unanswered questions"
        aside={`${suggestableGaps.length} unanswered`}
        onClose={() => setShowAllSuggestions(false)}
      >
        <ol className="bb-modal-list">
          {suggestableGaps.map((g, i) => (
            <li key={i} className="bb-modal-row">
              <span className="bb-modal-rank">{i + 1}</span>
              <div className="bb-modal-body-col">
                <span className="bb-modal-row-title">{g.topic}</span>
                <span className="bb-modal-row-sub">"{g.example}" · {g.count} {g.count === 1 ? 'ask' : 'asks'}</span>
              </div>
              <button
                type="button"
                className="bb-modal-row-action"
                disabled={draftMutation.isPending}
                onClick={() => draftFromGap(g)}
              >
                Draft FAQ →
              </button>
            </li>
          ))}
        </ol>
      </ViewAllModal>

    </section>
  )
}
